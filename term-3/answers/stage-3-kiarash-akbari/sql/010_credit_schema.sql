-- Stage 3, step 1: the credit dataset gets its own schema in the stage-2 database.
--
-- Two rules this file follows on purpose.
--
-- * Floats are `double precision`, never `numeric`. PostgreSQL rejects NaN in
--   `numeric`, and the loader maps an empty field to NULL so that missingness is
--   countable in SQL (see credit.v_column_missingness). Integral-looking values
--   are also `double precision` because nothing in the file guarantees "3" over
--   "3.0"; only the row id and the label are integers.
-- * No CHECK constrains a range that has not been measured against the real file.
--   Stage 2's `ck_factory_case_file_order` aborted a full load because the
--   November hour repeats once and the DDL assumed a naive comparison; the domain
--   rules that are certain - the label is 0 or 1, a hash is 64 hex characters -
--   are the only ones kept here. Everything else is validated by the loader,
--   quarantined with a reason, and reported.
--
-- There is deliberately no secondary index: the model reads every row once, and
-- stage 2 measured what an index costs on insert. A future query that filters
-- cohorts repeatedly would earn one, with a plan as evidence.

-- No BEGIN/COMMIT here: apply_sql_migrations runs each file inside one
-- transaction it owns, and stage 2's migrations rely on that. A nested BEGIN
-- would only warn that a transaction is already open and hide the rollback.

CREATE SCHEMA IF NOT EXISTS credit;

CREATE TABLE IF NOT EXISTS credit.application (
    row_id                            bigint        NOT NULL,
    serious_dlqin_2yrs                smallint      NOT NULL,
    revolving_utilization_unsecured   double precision,
    age                               double precision,
    num_late_30_59                    double precision,
    debt_ratio                        double precision,
    monthly_income                    double precision,
    num_open_credit_lines             double precision,
    num_late_90                       double precision,
    num_real_estate_loans             double precision,
    num_late_60_89                    double precision,
    num_dependents                    double precision,
    CONSTRAINT pk_credit_application PRIMARY KEY (row_id),
    CONSTRAINT ck_credit_application_target CHECK (serious_dlqin_2yrs IN (0, 1))
);

COMMENT ON TABLE credit.application IS
    'One applicant row as the file states it. Raw: sentinel codes stay here, and '
    'credit.v_model_input is where they stop being numbers.';
COMMENT ON COLUMN credit.application.num_late_30_59 IS
    'Bureau count of 30-59 day past-due events, codes included. The view replaces '
    'the codes with NULL; this column keeps the file as it arrived.';
COMMENT ON COLUMN credit.application.revolving_utilization_unsecured IS
    'Revolving balance over revolving limit. Values above 1 are common enough to '
    'keep rather than reject; the view caps them and keeps the excess visible.';

-- Provenance, same shape as factory.load_run so one habit covers both schemas.
CREATE TABLE IF NOT EXISTS credit.load_run (
    run_id        integer GENERATED BY DEFAULT AS IDENTITY,
    source_kind   text        NOT NULL,
    file_name     text        NOT NULL,
    sha256        char(64)    NOT NULL,
    rows_loaded   bigint      NOT NULL,
    rejected_count bigint     NOT NULL DEFAULT 0,
    fingerprint   char(12)    NOT NULL,
    loaded_at     timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT pk_credit_load_run PRIMARY KEY (run_id),
    CONSTRAINT ck_credit_load_run_sha CHECK (sha256 ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_credit_load_run_fingerprint CHECK (fingerprint ~ '^[0-9a-f]{12}$'),
    CONSTRAINT ck_credit_load_run_rows CHECK (rows_loaded >= 0),
    CONSTRAINT ck_credit_load_run_rejected CHECK (rejected_count >= 0),
    CONSTRAINT ck_credit_load_run_kind CHECK (source_kind = 'file')
);

COMMENT ON TABLE credit.load_run IS
    'What was loaded, from which file, hashed the way stage 1 hashes outputs. The '
    'column names match factory.load_run, so one provenance habit covers both '
    'schemas. A re-downloaded but unchanged file keeps the same fingerprint; the '
    'sha is what changes, and it is recorded rather than relied on.';